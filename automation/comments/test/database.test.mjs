import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
test('atomic claim, cap, stale content, cancellation and single publication', async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create table auth.users(id uuid primary key); create table public.profiles(id uuid primary key,status text); create table public.posts(id bigint primary key,author_id uuid,title text,short_description text,description text,status text,is_seed boolean,published_at timestamptz,expires_at timestamptz);`);
 await db.exec(await readFile(new URL('../../../supabase/migrations/0014_post_comments.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../../../supabase/migrations/0015_auto_post_comments.sql',import.meta.url),'utf8'));
 const scalar=async(q)=>(await db.query(q)).rows[0].v;
 await db.exec(`insert into profiles values('11111111-1111-1111-1111-111111111111','active'); insert into posts values(1,'11111111-1111-1111-1111-111111111111','테스트','서비스','본문','active',false,now()-interval '20 minutes',null); update auto_comment_settings set start_at=now()-interval '1 hour',daily_limit=1;`);
 assert.equal(await scalar('select claim_auto_comment() v'),null);
 await db.exec('update auto_comment_settings set enabled=true');
 assert.equal((await scalar('select claim_auto_comment() v')).id,1);
 assert.equal(await scalar('select claim_auto_comment() v'),null);
 assert.equal(await scalar("select finish_auto_comment(1,'체험 가능한 시간을 안내해 주실 수 있나요?') v"),true);
 assert.equal(await scalar("select finish_auto_comment(1,'체험 가능한 시간을 안내해 주실 수 있나요?') v"),false);
 assert.equal(await scalar('select nickname v from post_comments'),'홍보회원 2455');
 await db.exec('delete from posts where id=1');
 assert.equal(await scalar('select attempts v from auto_comment_daily_budget'),1);
 await db.exec(`update auto_comment_settings set daily_limit=5; insert into posts values(2,'11111111-1111-1111-1111-111111111111','테스트','서비스','본문','active',false,now()-interval '20 minutes',null);`);
 await scalar('select claim_auto_comment() v');
 await db.exec("update posts set title='변경' where id=2");
 assert.equal(await scalar("select finish_auto_comment(2,'체험 가능한 시간을 안내해 주실 수 있나요?') v"),false);
 await db.exec(`insert into posts values(3,'11111111-1111-1111-1111-111111111111','테스트','서비스','본문','active',false,now()-interval '20 minutes',null);`);
 await scalar('select claim_auto_comment() v'); await db.exec('update auto_comment_settings set enabled=false');
 assert.equal(await scalar("select finish_auto_comment(3,'체험 가능한 시간을 안내해 주실 수 있나요?') v"),false);
 await db.close();
});
