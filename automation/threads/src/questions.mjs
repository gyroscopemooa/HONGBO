const GENERAL = ['이런 소식은 평소 어디서 찾아보시나요?', '여러분은 어떤 점이 가장 궁금하신가요?', '선택하기 전에 가장 먼저 확인하는 건 무엇인가요?'];
export function promoQuestion(post) {
  // Title/summary take precedence over incidental words in the long description.
  const primary = [post.title, post.short_description].join(' ').normalize('NFKC');
  const match = TOPICS.find(([pattern]) => pattern.test(primary));
  const questions = match?.[1] ?? GENERAL;
  return questions[Math.abs(Number(post.post_id) || 0) % questions.length];
}
