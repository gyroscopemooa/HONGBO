-- 홈 대형 슬라이드(Hero) 광고
-- 읽기·쓰기는 서버(service_role)를 통해서만 한다. 기존 테이블은 변경하지 않는다.
create table if not exists public.hero_ads (
  id bigint generated by default as identity primary key,
  requested_by uuid references public.profiles (id) on delete set null,
  plan text not null check (plan in ('week', 'month')),
  status text not null default 'requested' check (status in ('requested', 'active')),
  design_mode text not null check (design_mode in ('template', 'image', 'discuss')),
  title text check (title is null or char_length(title) <= 40),
  subtitle text check (subtitle is null or char_length(subtitle) <= 80),
  button_text text check (button_text is null or char_length(button_text) <= 16),
  theme text not null default 'violet' check (theme in ('violet', 'blue', 'mint', 'coral', 'dark')),
  image_url text check (image_url is null or char_length(image_url) <= 2100),
  link_mode text not null check (link_mode in ('url', 'discuss')),
  link_url text check (link_url is null or char_length(link_url) <= 2100),
  memo text check (memo is null or char_length(memo) <= 500),
  advertiser text check (advertiser is null or char_length(advertiser) <= 60),
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists hero_ads_status on public.hero_ads (status, ends_at);
create index if not exists hero_ads_requester on public.hero_ads (requested_by, created_at desc);
alter table public.hero_ads enable row level security;
revoke all on public.hero_ads from public, anon, authenticated;
grant all on public.hero_ads to service_role;
