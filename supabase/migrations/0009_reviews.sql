-- 후기·리뷰 게시판 (회원이 업체·서비스 이용 후기를 별점과 함께 작성)
-- 읽기·쓰기는 서버(service_role)를 통해서만 한다. 기존 테이블은 변경하지 않는다.
create table if not exists public.review_posts (
  id bigint generated by default as identity primary key,
  author_id uuid references public.profiles (id) on delete set null,
  category text not null check (char_length(category) between 2 and 20),
  target_name text not null check (char_length(target_name) between 2 and 60),
  rating smallint not null check (rating between 1 and 5),
  title text not null check (char_length(title) between 2 and 80),
  body text not null check (char_length(body) between 10 and 3000),
  images text[] not null default '{}' check (cardinality(images) <= 4),
  youtube_id text check (youtube_id is null or char_length(youtube_id) = 11),
  target_url text check (target_url is null or char_length(target_url) <= 2100),
  status text not null default 'active' check (status in ('active', 'hidden', 'deleted')),
  created_at timestamptz not null default now()
);
create index if not exists review_posts_recent on public.review_posts (status, created_at desc);
create index if not exists review_posts_category on public.review_posts (status, category, created_at desc);
create index if not exists review_posts_author on public.review_posts (author_id, created_at desc);
alter table public.review_posts enable row level security;
revoke all on public.review_posts from public, anon, authenticated;
grant all on public.review_posts to service_role;

create table if not exists public.review_reports (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.review_posts (id) on delete cascade,
  reporter_id uuid references auth.users (id) on delete set null,
  reporter_anon text not null,
  reason text not null check (char_length(reason) between 1 and 30),
  detail text check (detail is null or char_length(detail) <= 500),
  created_at timestamptz not null default now(),
  unique (review_id, reporter_anon)
);
alter table public.review_reports enable row level security;
revoke all on public.review_reports from public, anon, authenticated;
grant all on public.review_reports to service_role;
