-- 유료 광고: 상단 프리미엄 10칸 / 와이드 배너. 신청 → 운영자 승인 → 기간 노출.
-- 서버(service_role)에서만 읽고 쓴다.
create table if not exists public.ads (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts (id) on delete cascade,
  kind text not null check (kind in ('premium', 'banner')),
  plan text not null check (plan in ('week', 'month')),
  status text not null default 'requested' check (status in ('requested', 'active')),
  slot_no integer check (slot_no between 1 and 10),
  starts_at timestamptz,
  ends_at timestamptz,
  requested_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists ads_live_idx on public.ads (kind, status, ends_at);
create index if not exists ads_post_idx on public.ads (post_id);
alter table public.ads enable row level security;
revoke all on public.ads from anon, authenticated;
grant all on public.ads to service_role;
