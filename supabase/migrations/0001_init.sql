create extension if not exists pg_trgm;

-- ───────────── profiles ─────────────
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nickname text not null,
  avatar_url text,
  email text,
  status text not null default 'active' check (status in ('active', 'blocked')),
  created_at timestamptz not null default now()
);

-- ───────────── posts ─────────────
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  author_id uuid references public.profiles (id) on delete set null,
  category text not null check (category in ('apps','websites','services','offline','products','content','events','free')),
  title text not null check (char_length(title) between 1 and 120),
  short_description text not null,
  description text not null,
  primary_image_url text,
  external_url text not null check (external_url ~* '^https?://'),
  platform text,
  price text,
  region text,
  address text,
  map_url text,
  tags text[] not null default '{}',
  extra jsonb not null default '{}'::jsonb,
  contact text,
  status text not null default 'active' check (status in ('active','hidden','blocked','expired','deleted')),
  admin_pinned boolean not null default false,
  curated_rank integer,
  is_seed boolean not null default false,
  view_count integer not null default 0,
  click_count integer not null default 0,
  popularity integer generated always as (view_count + click_count * 3) stored,
  search_text text not null default '',
  published_at timestamptz not null default now(),
  bumped_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz
);

create index if not exists posts_status_bumped_idx on public.posts (status, bumped_at desc);
create index if not exists posts_category_bumped_idx on public.posts (category, status, bumped_at desc);
create index if not exists posts_region_idx on public.posts (region) where region is not null;
create index if not exists posts_author_idx on public.posts (author_id, published_at desc);
create index if not exists posts_seed_idx on public.posts (is_seed) where is_seed;
create index if not exists posts_pinned_idx on public.posts (admin_pinned, curated_rank) where admin_pinned;
create index if not exists posts_search_trgm_idx on public.posts using gin (search_text gin_trgm_ops);

-- 검색용 컬럼(제목/한 줄 소개/상세 설명/태그)을 저장 시점에 갱신
create or replace function public.posts_before_write() returns trigger
language plpgsql as $$
begin
  new.search_text := lower(
    coalesce(new.title, '') || ' ' ||
    coalesce(new.short_description, '') || ' ' ||
    coalesce(new.description, '') || ' ' ||
    coalesce(array_to_string(new.tags, ' '), '')
  );
  return new;
end;
$$;

drop trigger if exists posts_before_write on public.posts;
create trigger posts_before_write
  before insert or update on public.posts
  for each row execute function public.posts_before_write();

