-- ───────────── analytics_events (가볍게 시작) ─────────────
create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  post_id bigint references public.posts (id) on delete cascade,
  anonymous_id text,
  user_id uuid,
  created_at timestamptz not null default now()
);
create index if not exists events_created_idx on public.analytics_events (created_at desc);
create index if not exists events_post_idx on public.analytics_events (post_id, created_at desc);
create index if not exists events_dedupe_idx on public.analytics_events (event_type, post_id, anonymous_id, created_at desc);

-- ───────────── 함수 ─────────────
create or replace function public.bump_post_counter(p_post_id bigint, p_kind text) returns void
language sql security definer set search_path = public as $$
  update public.posts
     set view_count  = view_count  + (case when p_kind = 'view'  then 1 else 0 end),
         click_count = click_count + (case when p_kind = 'click' then 1 else 0 end)
   where id = p_post_id;
$$;

create or replace function public.popular_scores(p_hours integer, p_limit integer)
returns table (post_id bigint, score bigint)
language sql security definer set search_path = public as $$
  select e.post_id,
         sum(case e.event_type when 'post_view' then 1 when 'external_click' then 3 else 0 end)::bigint as score
    from public.analytics_events e
    join public.posts p on p.id = e.post_id
   where e.created_at > now() - make_interval(hours => p_hours)
     and e.post_id is not null
     and p.status = 'active'
   group by e.post_id
  having sum(case e.event_type when 'post_view' then 1 when 'external_click' then 3 else 0 end) > 0
   order by score desc
   limit p_limit;
$$;

revoke all on function public.bump_post_counter(bigint, text) from public, anon, authenticated;
revoke all on function public.popular_scores(integer, integer) from public, anon, authenticated;
grant execute on function public.bump_post_counter(bigint, text) to service_role;
grant execute on function public.popular_scores(integer, integer) to service_role;

-- ───────────── RLS ─────────────
-- 서버(service_role)는 RLS 를 우회합니다. 공개 키(anon)로는 공개 데이터만 읽을 수 있습니다.
alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.post_images enable row level security;
alter table public.reports enable row level security;
alter table public.banners enable row level security;
alter table public.notices enable row level security;
alter table public.analytics_events enable row level security;

drop policy if exists "profiles read own" on public.profiles;
create policy "profiles read own" on public.profiles for select to authenticated using (auth.uid() = id);

drop policy if exists "posts public read" on public.posts;
create policy "posts public read" on public.posts for select to anon, authenticated
  using (status = 'active' and (expires_at is null or expires_at > now()));

drop policy if exists "post_images public read" on public.post_images;
create policy "post_images public read" on public.post_images for select to anon, authenticated
  using (exists (select 1 from public.posts p where p.id = post_id and p.status = 'active'));

drop policy if exists "banners public read" on public.banners;
create policy "banners public read" on public.banners for select to anon, authenticated using (is_active);

drop policy if exists "notices public read" on public.notices;
create policy "notices public read" on public.notices for select to anon, authenticated using (true);

