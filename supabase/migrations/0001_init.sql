create index if not exists reports_post_idx on public.reports (post_id);

-- ───────────── banners / notices ─────────────
create table if not exists public.banners (
  id bigint generated by default as identity primary key,
  title text not null,
  subtitle text,
  image_url text,
  target_url text not null,
  placement text not null default 'side' check (placement in ('side', 'strip')),
  theme text not null default 'coral' check (theme in ('coral', 'blue', 'mint', 'violet', 'amber')),
