-- 1) 한줄홍보 카테고리: 카테고리 허용 목록에 quick 추가, 링크는 선택 사항
alter table public.posts drop constraint if exists posts_category_check;
alter table public.posts add constraint posts_category_check
  check (category in ('apps','websites','services','offline','products','content','events','free','quick'));
alter table public.posts alter column external_url drop not null;

-- 2) 홍보소모임 자유게시판. 읽기·쓰기는 서버(service_role)를 통해서만 한다.
create table if not exists public.meetup_posts (
  id bigint generated by default as identity primary key,
  author_id uuid references public.profiles (id) on delete set null,
  title text not null check (char_length(title) between 2 and 80),
  body text not null check (char_length(body) between 2 and 3000),
  status text not null default 'active' check (status in ('active', 'deleted')),
  created_at timestamptz not null default now()
);
create index if not exists meetup_posts_recent on public.meetup_posts (status, created_at desc);
create index if not exists meetup_posts_author on public.meetup_posts (author_id, created_at desc);
alter table public.meetup_posts enable row level security;
revoke all on public.meetup_posts from anon, authenticated;
grant all on public.meetup_posts to service_role;
