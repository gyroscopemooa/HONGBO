import assert from "node:assert/strict";
import { PLAY_PLACES } from "../src/data/play";
import { PLAY_SORTS, playStatus, sortPlayPlacesBy } from "../src/lib/play";
const day = "2026-11-15";
const slugs = (s: Parameters<typeof sortPlayPlacesBy>[1]) => sortPlayPlacesBy(PLAY_PLACES, s, day);
const dl = slugs("deadline").filter(p => p.endDate && !p.schedulePending);
for (let i = 1; i < dl.length; i++) assert((dl[i-1].endDate!) <= dl[i].endDate!, "deadline order");
assert(slugs("deadline").every(p => playStatus(p, day) !== "종료"));
assert(slugs("ongoing").every(p => playStatus(p, day) === "진행 중") && slugs("ongoing").length > 0);
assert(slugs("past").every(p => playStatus(p, day) === "종료") && slugs("past").length > 0);
const lg = slugs("longest").filter(p => p.startDate && p.endDate && !p.schedulePending);
const len = (p: typeof lg[number]) => Date.parse(p.endDate!) - Date.parse(p.startDate!);
for (let i = 1; i < lg.length; i++) assert(len(lg[i-1]) >= len(lg[i]), "longest order");
const dd = slugs("dday").filter(p => p.startDate && !p.schedulePending).map(p => p.startDate! < day ? day : p.startDate!);
for (let i = 1; i < dd.length; i++) assert(dd[i-1] <= dd[i], "dday order");
const lt = slugs("latest"); for (let i = 1; i < lt.length; i++) assert(lt[i-1].checkedAt >= lt[i].checkedAt);
assert.equal(slugs("default").length, sortPlayPlacesBy(PLAY_PLACES, "default", day).length);
assert.equal(PLAY_SORTS.length, 7);
console.log("PASS: sort modes (latest, deadline, D-day, ongoing, longest, past) order and filter correctly.");
