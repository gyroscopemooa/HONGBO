import assert from "node:assert/strict";
import { PLAY_PLACES } from "../src/data/play";
import { filterPlayPlaces, koreanDay, playStatus, playPeriod, validPlayDate, PLAY_PERIOD_NOTE } from "../src/lib/play";
import { parsePostInput } from "../src/lib/validation";

const festival = PLAY_PLACES.find(p=>p.slug==="busan-fireworks-2026")!;
assert.equal(koreanDay(new Date("2026-11-07T15:00:00Z")), "2026-11-08");
assert.equal(playStatus(festival, "2026-11-06"), "예정");
assert.equal(playStatus(festival, "2026-11-07"), "진행 중");
assert.equal(playStatus(festival, "2026-11-08"), "종료");
assert.equal(playPeriod(festival), "2026.11.07 (토)");
assert.equal(playPeriod({startDate:"2026-11-07",endDate:"2026-11-08"}), "2026.11.07 (토) ~ 2026.11.08 (일)");
assert.equal(playPeriod({}), "상시 장소 안내 · 방문일 운영 확인");
assert(!validPlayDate("2026-02-29"));
assert(validPlayDate("2028-02-29"));
assert(!validPlayDate("2026-13-01"));
assert(!filterPlayPlaces(PLAY_PLACES, {}, "2026-11-11").some(p=>p.slug===festival.slug));
assert(filterPlayPlaces(PLAY_PLACES, {ended:true}, "2026-11-11").some(p=>p.slug===festival.slug));
assert(filterPlayPlaces(PLAY_PLACES, {region:"부산", companion:"아이와", kind:"체험·놀거리", q:"바다"}, "2026-11-11").some(p=>p.slug==="blueline-park"));
assert.equal(filterPlayPlaces(PLAY_PLACES, {region:"제주"}).length, 0);
assert.equal(new Set(PLAY_PLACES.map(p=>p.slug)).size, PLAY_PLACES.length);
for (const p of PLAY_PLACES) { assert.equal(new URL(p.source).protocol, "https:"); if(p.benefitUrl) assert.equal(new URL(p.benefitUrl).protocol, "https:"); }
const input = {category:"offline",title:"나들이 공방 안내",shortDescription:"아이와 함께 체험하는 공방",description:"직접 예약해서 방문할 수 있는 도자기 체험 안내입니다.",region:"부산",address:"부산 해운대구",tags:["놀러가자","체험·놀거리","아이와"],extra:{businessUrl:"https://www.bluelinepark.com/",benefits:"discount",links:[]}};
const valid=parsePostInput(input);
assert(valid.ok);
assert(valid.data.tags.includes("놀러가자"));
assert(valid.data.extra.benefits?.includes("discount"));
const withPeriod = parsePostInput({...input, extra:{...input.extra,notes:[{title:PLAY_PERIOD_NOTE, body:playPeriod({startDate:"2026-11-07",endDate:"2026-11-08"})}]}});
assert(withPeriod.ok);
assert.equal(withPeriod.data.extra.notes?.[0].body, "2026.11.07 (토) ~ 2026.11.08 (일)");
assert(!parsePostInput({...input,extra:{businessUrl:"javascript:alert(1)"}}).ok);
console.log("Play: Korean event boundaries, filters, content integrity and share validation passed.");
