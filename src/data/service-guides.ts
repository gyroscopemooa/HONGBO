export function matchingServiceGuides(query: string) {
  const normalize = (s: string) => s.toLowerCase().replace(/\s+/g, "");
  const terms = query.trim().split(/\s+/).filter(Boolean).map(normalize);
  return terms.length ? SERVICE_GUIDES.filter(g => terms.every(t => normalize([g.title, g.description, ...g.keywords].join(" ")).includes(t))) : [];
}
